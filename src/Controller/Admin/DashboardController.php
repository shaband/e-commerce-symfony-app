    public function configureDashboard(): Dashboard
    {
        return Dashboard::new()
            ->setTitle('Symfony')
            ->renderContentMaximized()
            ->setDefaultColorScheme('dark');

    }

    public function configureAssets(): Assets
    {
        return parent::configureAssets()
            ->addJsFile('https://cdn.jsdelivr.net/npm/htmx.org@2.0.10/dist/htmx.min.js')
            ->addJsFile("admin/js/scripts.js"); // TODO: Change the autogenerated stub
    }

    public function configureMenuItems(): iterable
    {
        yield MenuItem::linkToDashboard('Dashboard', 'fa fa-home');
        yield MenuItem::linkTo(SettingCrudController::class, "Settings", 'fa fa-cog');
        yield MenuItem::section('Users', 'fa fa-users');
        yield MenuItem::linkTo(UserCrudController::class, 'Users', 'fa fa-user');
        yield MenuItem::linkTo(AdminCrudController::class, 'Admin', 'fa fa-shield');
        yield MenuItem::section('Products', 'fa fa-shopping-basket');
        yield MenuItem::linkTo(CategoryCrudController::class, 'Categories', 'fa fa-list');

        yield MenuItem::section('Others', 'fa fa-ellipsis-v');

        yield MenuItem::linkTo(SliderCrudController::class, 'Sliders', 'fa fa-sliders');
        yield MenuItem::linkTo(SponsorsCrudController::class, 'Sponsors', 'fa fa-handshake');
        yield MenuItem::linkTo(TestimonialCrudController::class, 'Testimonials', 'fa fa-quote-right');

    }
